const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');
const os = require('os');
const EDGE = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const PORT = 19223;
const OUT = path.join(process.cwd(), 'docs', 'screenshots', 'v2.14.0-mobile');
fs.mkdirSync(OUT, { recursive: true });
const profile = path.join(os.tmpdir(), 'edge-gp-mobile-profile2');
fs.rmSync(profile, { recursive: true, force: true });
const child = spawn(EDGE, ['--headless=new', `--remote-debugging-port=${PORT}`, `--user-data-dir=${profile}`, '--no-first-run', '--no-default-browser-check', '--disable-gpu', '--hide-scrollbars', 'about:blank'], { stdio: 'ignore' });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function main() {
  let target = null;
  for (let i = 0; i < 60; i += 1) { try { const list = await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json(); target = list.find((t) => t.type === 'page'); if (target) break; } catch {} await sleep(200); }
  const ws = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
  let id = 0; const pending = new Map(); const errors = [];
  ws.onmessage = (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { const { res, rej } = pending.get(m.id); pending.delete(m.id); if (m.error) rej(new Error(m.error.message)); else res(m.result); } else if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.text); else if (m.method === 'Runtime.consoleAPICalled' && m.params.type === 'error') errors.push(m.params.args.map((a) => a.value || a.description || '').join(' ')); };
  const send = (method, params = {}) => new Promise((res, rej) => { const mid = ++id; pending.set(mid, { res, rej }); ws.send(JSON.stringify({ id: mid, method, params })); });
  const evaluate = async (expression) => { const r = await send('Runtime.evaluate', { expression, returnByValue: true, awaitPromise: true }); if (r.exceptionDetails) throw new Error(r.exceptionDetails.text); return r.result ? r.result.value : undefined; };
  const shot = async (name) => { const r = await send('Page.captureScreenshot', { format: 'png', fromSurface: true }); fs.writeFileSync(path.join(OUT, name + '.png'), Buffer.from(r.data, 'base64')); console.log('shot', name); };
  await send('Page.enable'); await send('Runtime.enable');
  await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 2, mobile: true });
  await send('Emulation.setTouchEmulationEnabled', { enabled: true, maxTouchPoints: 5 });
  await send('Page.navigate', { url: 'http://127.0.0.1:18090/login.html' }); await sleep(1800);
  await evaluate(`document.getElementById('username').value='mobiletest';document.getElementById('password').value='mobile12345';document.getElementById('remember').checked=true;document.getElementById('authForm').requestSubmit();`); await sleep(3200);
  await evaluate(`location.hash='#paper'`); await sleep(6000);
  await evaluate(`document.querySelector('#view-paper').scrollIntoView({block:'start'})`); await sleep(500);
  console.log('trade rows default', await evaluate(`document.querySelectorAll('.paper-trade-table tbody tr').length`));
  console.log('toggle text', await evaluate(`(document.querySelector('#paperTradesToggle')||{}).textContent||''`));
  await evaluate(`document.querySelector('#paperTradesToggle').click()`); await sleep(600);
  console.log('trade rows expanded', await evaluate(`document.querySelectorAll('.paper-trade-table tbody tr').length`));
  await evaluate(`document.querySelector('.paper-trade-head').scrollIntoView({block:'start'})`); await sleep(300);
  await shot('07-trades-expanded-8');
  await evaluate(`document.querySelector('#paperTradesToggle').click()`); await sleep(400);
  await evaluate(`document.querySelector('[data-paper-open]').click()`); await sleep(7000);
  console.log('minute note', await evaluate(`(document.querySelector('#paperHoldingChartNote')||{}).textContent||''`));
  await shot('08-holding-minute-fallback');
  await evaluate(`document.querySelector('[data-paper-holding-tab="five"]').click()`); await sleep(7000);
  await shot('09-holding-five');
  await evaluate(`document.querySelector('[data-paper-holding-tab="month"]').click()`); await sleep(12000);
  console.log('month empty?', await evaluate(`(document.querySelector('#paperHoldingChart')||{}).textContent`));
  await shot('10-holding-month');
  console.log('console errors', errors);
  ws.close(); child.kill();
}
main().catch((err) => { console.error(err); try { child.kill(); } catch {}; process.exit(1); });
